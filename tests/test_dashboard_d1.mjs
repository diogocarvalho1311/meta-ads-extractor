import assert from 'node:assert/strict';
import { metricRows, readMetricTable } from '../cloudflare/reader.js';
import { SCHEMA as LUCRI } from '../cloudflare/lucri-dashboard-patch/functions/_trafego-schema.js';
import { onRequestGet } from '../cloudflare/lucri-dashboard-patch/functions/api/trafego/[tabela].js';
import { onRequest as cwbData } from '../CWB KIDS/dashboard/functions/api/data.js';
import { createSessionToken, COOKIE_NAME } from '../CWB KIDS/dashboard/lib/session.js';
const spec = LUCRI['meta-campanhas'];
const records = [{ id: 'm1', data: '2025-10-20', campanha: 'Teste', ctr_pct: 2.5, investimento: 123.45 }];
const formatted = metricRows(spec, records, true)[0];
assert.equal(formatted.DATA, '20/10/2025');
assert.equal(formatted['CTR (LINK)'], '2.5%');
assert.equal(formatted.INVESTIMENTO, 123.45);
assert.equal(metricRows(spec, records)[0]['CTR (LINK)'], 0.025);
assert.equal(metricRows(spec, [{ data: '2026-10-20', ctr_pct: null }])[0]['CTR (LINK)'], '');
let lastSql, lastParams;
const db = { prepare(sql) { lastSql = sql; return { bind(...params) { lastParams = params; return { async all() { return { results: records }; } }; } }; } };
await readMetricTable(db, spec, '2026-10-01', '2026-10-20');
assert.ok(lastSql.includes('data >= ? AND data <= ?'));
assert.deepEqual(lastParams, ['2026-10-01', '2026-10-20']);
let result = await onRequestGet({ request: new Request('https://example.com/api/trafego/meta-campanhas?format=sheet'), env: { METRICAS_DB: db }, params: { tabela: 'meta-campanhas' } });
assert.equal(result.status, 200);
assert.equal((await result.json()).rows[0].DATA, '20/10/2025');
result = await onRequestGet({ request: new Request('https://example.com/api/trafego/crm-leads'), env: { METRICAS_DB: db }, params: { tabela: 'crm-leads' } });
assert.equal(result.status, 404);
result = await cwbData({ request: new Request('https://example.com/api/data'), env: { DASHBOARD_PASSWORD: 'test-only' } });
assert.equal(result.status, 401);
const token = await createSessionToken('test-only');
result = await cwbData({ request: new Request('https://example.com/api/data', { headers: { Cookie: `${COOKIE_NAME}=${token}` } }), env: { DASHBOARD_PASSWORD: 'test-only', METRICAS_DB: db } });
assert.equal(result.status, 200);
assert.equal(result.headers.get('X-Metrics-Source'), 'cloudflare-d1');
const data = await result.json();
assert.equal(data.metaCampanhas[0].DATA, '2025-10-20');
assert.equal(data.metaCampanhas[0]['CTR (LINK)'], 0.025);
assert.deepEqual(data.insights, []);
console.log('Dashboard D1: datas, percentuais, filtros, CRM privado e autenticacao CWB validados.');
